  const CATALOG = { ja, en };
  const root = globalThis.document?.documentElement || { dataset: {} };

  function normalize(tag) {
    const primary = String(tag || "").trim().replace(/_/g, "-").split("-")[0].toLowerCase();
    return SUPPORTED.includes(primary) ? primary : null;
  }

  function browserLocale(nav) {
    const list = nav?.languages?.length ? Array.from(nav.languages) : nav?.language ? [nav.language] : [];
    if (!list.length) return null;
    for (const tag of list) {
      const found = normalize(tag);
      if (found) return found;
    }
    return FALLBACK;
  }

  const choice = normalize(root.dataset?.locale) || "";
  const locale = choice || browserLocale(globalThis.navigator) || FALLBACK;

  function t(key, params) {
    let text = CATALOG[locale][key] ?? CATALOG[FALLBACK][key];
    if (text == null) return key;
    if (typeof text === "object") text = Number(params?.count) === 1 ? text.one : text.other;
    if (!params) return text;
    return text.replace(/\{(\w+)\}/g, (match, name) => (name in params ? String(params[name]) : match));
  }

  function apply(scope) {
    const holder = scope || globalThis.document;
    if (!holder?.querySelectorAll) return;
    holder.querySelectorAll("[data-i18n]").forEach((node) => {
      if (node.dataset?.i18n) node.textContent = t(node.dataset.i18n);
    });
    holder.querySelectorAll("[data-i18n-attr]").forEach((node) => {
      String(node.dataset?.i18nAttr || "").split(";").forEach((pair) => {
        const [name, key] = pair.split(":").map((part) => part.trim());
        if (name && key) node.setAttribute(name, t(key));
      });
    });
  }

  root.setAttribute?.("lang", locale);
  apply();
  globalThis.YataI18n = { SUPPORTED, FALLBACK, CATALOG, choice, locale, t, apply, normalize, browserLocale };
